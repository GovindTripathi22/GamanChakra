async function main() {
  console.log("Seeding baseline cost benchmark tables...");

  for (const b of BENCHMARK_SEEDS) {
    await prisma.costBenchmark.upsert({
      where: {
        destination_style_durationDays_travelers: {
          destination: b.destination,
          style: b.style,
          durationDays: b.durationDays,
          travelers: b.travelers,
        },
      },
      update: b,
      create: b,
    });
  }

  console.log(`Successfully seeded ${BENCHMARK_SEEDS.length} cost benchmark entries.`);
}

main()
  .catch((e) => {
    console.error("Seed error:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
